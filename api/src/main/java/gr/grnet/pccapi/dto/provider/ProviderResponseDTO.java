package gr.grnet.pccapi.dto.provider;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;
import gr.grnet.pccapi.dto.ContactDto;
import jakarta.validation.constraints.Pattern;
import lombok.Getter;
import org.eclipse.microprofile.openapi.annotations.enums.SchemaType;
import org.eclipse.microprofile.openapi.annotations.media.Schema;

import java.util.ArrayList;
import java.util.List;

/** A class that represents a Provider served as response by the Provider endpoint */
@Getter
@Schema(
    name = "ProviderResponse",
    description = "Provider is an organisation that hosts the handle service")
public class ProviderResponseDTO {

  @Schema(
      type = SchemaType.INTEGER,
      implementation = Integer.class,
      description = "The unique provider id generated by the database.",
      example = "1")
  public int id;

  @Schema(
      type = SchemaType.STRING,
      implementation = String.class,
      description = "The name of the provider .",
      example = "GRNET")
  public String name;

  @Schema(
          type = SchemaType.STRING,
          implementation = String.class,
          description = "The description of the provider .",
          example = "GRNET description provider")
  @JsonInclude(JsonInclude.Include.NON_NULL)
  public String description;

  @Schema(
          type = SchemaType.STRING,
          implementation = String.class,
          description = "Provider's logo URL or base64 encoded image data URI. " +
                  "Example URL: /logo/profile.jpg, or data URI: data:logo/png;base64,iVBORw0KGgo...",
          example = "https://logo/profile.jpg")
  @JsonProperty("logo")
  @JsonInclude(JsonInclude.Include.NON_NULL)
  public String logo;


  @Schema(
          type = SchemaType.ARRAY,
          implementation = ContactDto.class,
          description = "The contacts associated with this provider"
  )
  private List<ContactDto> contacts = new ArrayList<>();
}
